/**
 * Regenerates the docs site's script API reference, `docs-site/src/content/docs/reference/script-api.md`,
 * from the declarations every request script is type-checked against, so the published API can never
 * drift from what the checker enforces.
 *
 * `node scripts/docs-script-api.ts` writes the page; `node scripts/docs-script-api.ts --check` exits
 * non-zero when the committed page is out of date (this runs as part of `pnpm check`). The source
 * module has only type imports, so Node loads it straight from source.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { apiReference, type ApiReferenceSection } from '../packages/engine/src/script/types/api.ts';

const target = fileURLToPath(new URL('../docs-site/src/content/docs/reference/script-api.md', import.meta.url));

/** The reference page for `sections`. */
export function renderScriptApiReference(sections: readonly ApiReferenceSection[]): string {
  const lines = [
    '---',
    'title: Script API',
    'description: The declarations a request script is type-checked against, per protocol and phase.',
    '---',
    '',
    "<!-- Generated by `pnpm docs:script-api` from the engine's script declarations. Do not edit by hand. -->",
    '',
    'Every script sees the globals under **Every script**, and the `request` (and, after the response,',
    'the `response`) of its protocol and phase. The `Wb…Body` and `Wb…Message` types come from the',
    "request's contract — the operation's XSD elements, its OpenAPI schemas or its `.proto` messages —",
    'and are `unknown` when the request has none. `WbSecretName` is the union of the names the request',
    'lists under `scripts.secrets`. `WbStatus` is every HTTP status from 100 to 599 as a literal type,',
    'and `WbRange1` to `WbRange5` are its hundreds, so checking `response.status` narrows the response.',
    '',
    'A Postman script (`api: postman`) is JavaScript and is checked for syntax only; its `pm` object is',
    'described in the [Scripts guide](/wirebench/docs/guides/scripts/#postman-scripts).',
  ];
  for (const section of sections) {
    lines.push('', `## ${section.title}`, '', '```ts', section.declarations, '```');
  }
  return `${lines.join('\n')}\n`;
}

async function main(): Promise<void> {
  const rendered = renderScriptApiReference(apiReference());
  const check = process.argv.includes('--check');
  const current = await readFile(target, 'utf-8').catch(() => undefined);

  if (current === rendered) {
    process.stdout.write('docs-site reference/script-api.md is up to date\n');
    return;
  }
  if (check) {
    process.stderr.write('docs-site reference/script-api.md is out of date; run `pnpm docs:script-api`\n');
    process.exitCode = 1;
    return;
  }
  await writeFile(target, rendered, 'utf-8');
  process.stdout.write(`Wrote ${target}\n`);
}

if (process.argv[1] !== undefined && import.meta.url === new URL(process.argv[1], 'file:').href) {
  await main();
}
